defmodule AshLua.EvalActionsExtensionTest do
  @moduledoc """
  Fork-owned regression tests for the EvalActions extension seams:

    * runtime role-scoped entrypoint resolution (`entrypoints_resolver`) for
      both `:eval` and `:docs` (including the resolver-bypasses-cache
      property);
    * the app-supplied hardened base-VM hook (`lua_init`);
    * bounded timeout (static and `{M, F}` defaults, `timeout_ms` argument
      override, kill behavior, typed failure envelope);
    * distinct `lua_syntax_error` / `lua_runtime_error` classification;
    * `AddActions` no longer claims to run after every other transformer, so
      action wrappers generated by other extensions can bind to the
      synthesized actions (the wrapping itself is proven by the wrapper
      extension's own test suite).
  """

  use ExUnit.Case, async: false

  alias AshLua.Test.Posts.{
    DynamicTimeoutMCPActions,
    ExtensionMCPActions,
    Post,
    TimeoutMCPActions
  }

  describe "entrypoints_resolver seam" do
    test "resolver narrows the eval surface at call time" do
      {:ok, _} = Ash.create(Post, %{title: "Hello"}, action: :create)

      # narrow: true resolves read only — create is absent from the VM.
      probe_input =
        Ash.ActionInput.for_action(ExtensionMCPActions, :eval, %{
          script: "return type(posts.post.create)"
        })
        |> Ash.ActionInput.set_context(%{narrow: true})

      assert {:ok, %{result: "nil"}} = Ash.run_action(probe_input)

      # Calling the absent callable is a classified runtime failure, not a
      # silent success.
      narrow_input =
        Ash.ActionInput.for_action(ExtensionMCPActions, :eval, %{
          script: "return posts.post.create({ input = { title = \"x\" } })"
        })
        |> Ash.ActionInput.set_context(%{narrow: true})

      assert {:ok, %{result: nil, error: error}} = Ash.run_action(narrow_input)

      entry = unwrap(Map.new(error))
      assert entry["code"] == "lua_runtime_error"

      # The narrowed surface still exposes the read the resolver kept.
      read_input =
        Ash.ActionInput.for_action(ExtensionMCPActions, :eval, %{
          script: "return posts.post.read({ fields = { \"title\" } })[1].title"
        })
        |> Ash.ActionInput.set_context(%{narrow: true})

      assert {:ok, %{result: "Hello"}} = Ash.run_action(read_input)
    end

    test "resolver nil falls back to the static configured surface" do
      # No :narrow key in the context — resolver returns nil, static surface
      # (read + create on Post, read on Comment) applies.
      input =
        Ash.ActionInput.for_action(ExtensionMCPActions, :eval, %{
          script: "return type(posts.post.create)"
        })

      assert {:ok, %{result: "function"}} = Ash.run_action(input)
    end

    test "resolver result is exactly the docs surface (docs and eval agree)" do
      {:ok, _} = Ash.create(Post, %{title: "Docs scoped"}, action: :create)

      narrow_index =
        Ash.ActionInput.for_action(ExtensionMCPActions, :docs, %{})
        |> Ash.ActionInput.set_context(%{narrow: true})

      assert {:ok, index} = Ash.run_action(narrow_index)
      assert index =~ "posts.post.read"
      refute index =~ "posts.post.create"
      refute index =~ "posts.comment.read"

      static_index = Ash.ActionInput.for_action(ExtensionMCPActions, :docs, %{})
      assert {:ok, index} = Ash.run_action(static_index)
      assert index =~ "posts.post.read"
      assert index =~ "posts.post.create"
    end

    test "resolver returning [] exposes an empty surface (default-deny)" do
      # An explicitly empty list replaces the static filter — nothing is
      # callable and the docs index is empty of callables.
      input =
        Ash.ActionInput.for_action(ExtensionMCPActions, :eval, %{script: "return type(posts)"})
        |> Ash.ActionInput.set_context(%{narrow: :empty})

      assert {:ok, %{result: "nil"}} = Ash.run_action(input)

      docs =
        Ash.ActionInput.for_action(ExtensionMCPActions, :docs, %{})
        |> Ash.ActionInput.set_context(%{narrow: :empty})

      assert {:ok, index} = Ash.run_action(docs)
      refute index =~ "posts.post.read"
    end

    test "resolver scope and static scope coexist without cross-talk" do
      # Resolver-scoped manifests never route through for_eval_resource's
      # cache (they resolve [otp_app: ..., action_entrypoints: ...] directly),
      # so a narrowed call cannot be served a stale static manifest nor poison
      # one — proven behaviorally by interleaving narrow and static calls.
      {:ok, _} = Ash.create(Post, %{title: "Interleave"}, action: :create)

      for _ <- 1..3 do
        narrow_input =
          Ash.ActionInput.for_action(ExtensionMCPActions, :eval, %{
            script: "return type(posts.post.create)"
          })
          |> Ash.ActionInput.set_context(%{narrow: true})

        assert {:ok, %{result: "nil"}} = Ash.run_action(narrow_input)

        static_input =
          Ash.ActionInput.for_action(ExtensionMCPActions, :eval, %{
            script: "return type(posts.post.create)"
          })

        assert {:ok, %{result: "function"}} = Ash.run_action(static_input)
      end
    end
  end

  describe "lua_init seam" do
    test "the app-supplied base VM is what the script runs on" do
      input =
        Ash.ActionInput.for_action(ExtensionMCPActions, :eval, %{script: "return greeting"})

      assert {:ok, %{result: "hola"}} = Ash.run_action(input)
    end

    test "base-VM hardening carries through (removed stdlib stays removed)" do
      lua = ExtensionMCPActions.base_vm(%{})
      assert {["hola"], _} = Lua.eval!(lua, "return greeting")
    end
  end

  describe "timeout seam" do
    test "static default timeout kills a runaway script with a typed failure" do
      input =
        Ash.ActionInput.for_action(TimeoutMCPActions, :eval, %{script: "while true do end"})

      assert {:ok, %{result: nil, error: error}} = Ash.run_action(input)
      entry = unwrap(Map.new(error))

      assert entry["code"] == "lua_script_timeout"
      assert entry["message"] == "script timed out after 40ms"
    end

    test "dynamic {m, f} default timeout is consulted" do
      input =
        Ash.ActionInput.for_action(DynamicTimeoutMCPActions, :eval, %{
          script: "while true do end"
        })

      assert {:ok, %{result: nil, error: error}} = Ash.run_action(input)
      entry = unwrap(Map.new(error))

      assert entry["code"] == "lua_script_timeout"
      assert entry["message"] == "script timed out after 40ms"
    end

    test "the timeout_ms argument overrides the configured default" do
      input =
        Ash.ActionInput.for_action(TimeoutMCPActions, :eval, %{
          script: "while true do end",
          timeout_ms: 20
        })

      assert {:ok, %{result: nil, error: error}} = Ash.run_action(input)
      entry = unwrap(Map.new(error))

      assert entry["message"] == "script timed out after 20ms"
    end

    test "a fast script is unaffected by the timeout" do
      input =
        Ash.ActionInput.for_action(TimeoutMCPActions, :eval, %{script: "return 1 + 1"})

      assert {:ok, %{result: 2}} = Ash.run_action(input)
    end

    test "unconfigured timeout runs without a bound" do
      input =
        Ash.ActionInput.for_action(ExtensionMCPActions, :eval, %{script: "return 6 * 7"})

      assert {:ok, %{result: 42}} = Ash.run_action(input)
    end

    test "an invalid timeout_ms argument is a typed invalid argument" do
      input =
        Ash.ActionInput.for_action(TimeoutMCPActions, :eval, %{
          script: "return 1",
          timeout_ms: -5
        })

      assert {:error,
              %Ash.Error.Invalid{errors: [%Ash.Error.Action.InvalidArgument{field: :timeout_ms}]}} =
               Ash.run_action(input)
    end
  end

  describe "error classification seam" do
    test "compiler failures classify as lua_syntax_error with a single lead" do
      input =
        Ash.ActionInput.for_action(ExtensionMCPActions, :eval, %{
          script: "local x = 1 // not a lua comment"
        })

      assert {:ok, %{result: nil, error: error}} = Ash.run_action(input)
      entry = unwrap(Map.new(error))

      assert entry["code"] == "lua_syntax_error"
      assert String.starts_with?(entry["message"], "Lua syntax error: Failed to compile Lua!")
      refute entry["message"] =~ "Lua syntax error: Lua syntax error"
    end

    test "runtime failures classify as lua_runtime_error with the library message once" do
      input =
        Ash.ActionInput.for_action(ExtensionMCPActions, :eval, %{script: "missing_function()"})

      assert {:ok, %{result: nil, error: error}} = Ash.run_action(input)
      entry = unwrap(Map.new(error))

      assert entry["code"] == "lua_runtime_error"
      assert String.starts_with?(entry["message"], "Lua runtime error: ")
      refute entry["message"] =~ "Lua runtime error: Lua runtime error"
    end
  end

  describe "transformer ordering seam" do
    test "AddActions does not claim to run after every transformer" do
      # The catch-all `after?(_) -> true` made it impossible for any other
      # extension's transformer to deterministically run AFTER the actions
      # were synthesized (Spark's sorter skips mutually-contradictory
      # catch-alls, leaving only implicit registration order). Wrappers
      # consume the synthesized actions; they must be able to order after us.
      refute AshLua.EvalActions.Transformers.AddActions.after?(SomeOtherTransformer)
    end
  end

  defp unwrap(%{"errors" => [entry | _]}), do: Map.new(entry)
  defp unwrap(entry), do: entry
end
